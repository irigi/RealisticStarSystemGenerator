"""Phase 5 validation report: derived planet properties, Kozai-Lidov cycles and moons.

One draw of the stellar population with every planet model and moons attached (defaults).
Writes ``docs/validation/phase5_report.md`` and figures in ``docs/validation/figures/``; the
detailed checks are in :mod:`starsys.validation.derived`, :mod:`starsys.validation.moons` and
:mod:`starsys.validation.evolved`.

- formulae against the NASA Exoplanet Archive and known planets (Solar System, Proxima b,
  TRAPPIST-1);
- insolation-radius map of planets around main-sequence stars, with the habitable zone;
- habitable-zone planets per star by stellar type, spin states;
- Kozai-Lidov census and giant eccentricities with and without companions;
- moons: Solar System analogues, the Kepler limit, survival vs orbit, census;
- share of planets carrying each flag (including the new ``hz_extrapolated``, ``kozai``).

Usage: ``python -m starsys.validation.report5 [--systems 300000]``
"""

from __future__ import annotations

import argparse
import time
from datetime import date

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from .. import derived as dv  # noqa: E402
from .. import moons  # noqa: E402
from .. import planets  # noqa: E402
from ..paths import REPO_ROOT  # noqa: E402
from ..stars.population import draw_systems  # noqa: E402
from . import derived as vd  # noqa: E402
from . import moons as vm  # noqa: E402
from .report import FIG, _md, flag_shares  # noqa: E402

DOC = REPO_ROOT / "docs" / "validation" / "phase5_report.md"


def figure_insolation_radius(comp, pl, path):
    """Planets per main-sequence star in (insolation, radius), Sun-like and M-dwarf hosts."""
    teff = np.asarray(comp["teff"])
    ms = planets.hmc_hosts(comp) & (np.asarray(comp["phase"]) == 0)
    s_edges = np.logspace(-3, 4, 57)
    r_edges = np.logspace(np.log10(0.3), np.log10(25), 41)
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.5), sharey=True)
    for ax, (name, lo, hi) in zip(axes, (("G dwarfs (5300-6000 K)", 5300, 6000), ("M dwarfs (< 3900 K)", 2300, 3900))):
        hosts = ms & (teff >= lo) & (teff < hi)
        sel = (pl["host_kind"] == "S") & hosts[pl["component"]]
        h, _, _ = np.histogram2d(pl["insolation"][sel], pl["planet_radius"][sel], (s_edges, r_edges))
        h = h / hosts.sum()
        im = ax.pcolormesh(s_edges, r_edges, np.log10(np.where(h > 0, h, np.nan)).T, cmap="viridis", vmin=-5, vmax=-1.5)
        t = 0.5 * (lo + hi)
        lim = dv.s_eff(t, 1.0)
        ax.axvspan(lim["max_greenhouse"], lim["runaway"], color="tab:green", alpha=0.15, label="conservative HZ")
        ax.axvline(lim["recent_venus"], color="tab:green", ls=":", lw=1)
        ax.axvline(lim["early_mars"], color="tab:green", ls=":", lw=1)
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.invert_xaxis()
        ax.set_xlabel("insolation (Earth = 1)")
        ax.set_title(name)
        ax.legend(loc="upper right", fontsize=8)
    axes[0].set_ylabel("radius (Earth radii)")
    fig.colorbar(im, ax=axes, label="log10 planets per star per cell")
    fig.savefig(path, dpi=110, bbox_inches="tight")
    plt.close(fig)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--systems", type=int, default=300_000)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args(argv)
    FIG.mkdir(parents=True, exist_ok=True)

    systems, comp = draw_systems(args.systems, seed=args.seed)
    t1 = time.time()
    pl = planets.attach_planets(systems, comp, seed=args.seed + 1)
    t2 = time.time()
    m = moons.attach_moons(pl, comp, seed=args.seed + 2)
    t3 = time.time()
    no_kz = planets.attach_planets(systems, comp, seed=args.seed + 1, binaries=planets.bn.BinaryModel(kozai=False),
                                   derived=None)
    per = 1e5 / args.systems
    figure_insolation_radius(comp, pl, FIG / "insolation_radius.png")

    out = [
        "# Phase 5 report (generated)",
        "",
        f"Generated by `python -m starsys.validation.report5 --systems {args.systems}` on {date.today()}: "
        f"{args.systems:,} systems, {len(pl['period']):,} planets, {len(m['planet']):,} moons, all models at "
        "their defaults. Verdicts and context: [phase5.md](phase5.md).",
        "",
        f"Runtime per 100,000 systems: planets (with derived properties and Kozai-Lidov) {(t2 - t1) * per:.1f} s, "
        f"moons {(t3 - t2) * per:.2f} s.",
        "",
        "## Formulae against the NASA Exoplanet Archive",
        "",
        _md(vd.archive_check()),
        "",
        "## Known planets",
        "",
        _md(vd.known_planets()),
        "",
        "## Insolation and radius",
        "",
        "![Insolation-radius occurrence](figures/insolation_radius.png)",
        "",
        "## Habitable-zone planets per main-sequence star (S-type)",
        "",
        _md(vd.hz_census(comp, pl)),
        "",
        "Time conservative-HZ planets (< 10 Earth masses) spent in a runaway greenhouse after forming at "
        "10 Myr, while their star was brighter (Luger & Barnes 2015: tens to hundreds of Myr for M dwarfs):",
        "",
        _md(vd.runaway(comp, pl), ".1f"),
        "",
        "## Spin states",
        "",
        _md(vd.locking(comp, pl), ".1f"),
        "",
        "Rotation of free (not locked) planets (primordial spin, Kokubo & Genda 2010 for rocky planets, "
        "slowed by the stellar tide; spin-down by moons is not included):",
        "",
        _md(vd.rotation(comp, pl), ".1f"),
        "",
        "## Kozai-Lidov cycles",
        "",
        _md(vd.kozai_census(comp, pl, len(no_kz["period"]))),
        "",
        _md(vd.ecc_in_binaries(comp, pl)),
        "",
        "## Moons",
        "",
        "Solar System analogues (2000 draws each):",
        "",
        _md(vm.solar_system()),
        "",
        "Galilean-analogue moons of warm planets (Teachey+2018):",
        "",
        _md(vm.teachey(comp, pl, m)),
        "",
        "Survival vs orbit:",
        "",
        _md(vm.survival(comp, pl, m), ".1f"),
        "",
        _md(vm.census(comp, pl, m)),
        "",
        "## Flags",
        "",
        _md(flag_shares(pl).drop(index="moon"), ".1f"),
        "",
        "Every moon carries the `moon` flag and its planet's flags.",
        "",
    ]
    DOC.write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
